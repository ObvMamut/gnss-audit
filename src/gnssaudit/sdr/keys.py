_SIGNAL_ROLE = re.compile(r"^(Acquisition|Tracking|TelemetryDecoder)_([0-9A-Z][0-9A-Za-z]?)$")
_CHANNEL = re.compile(r"^Channel[0-9]+\.(satellite|RF_channel_ID)$")
_CHANNELS = re.compile(r"^Channels_[0-9A-Z][0-9A-Za-z]?\.(count|RF_channel_ID)$")


def is_verified(key: str) -> bool:
    """True if v0.0.22 reads this key."""
    if key == "Channels.in_acquisition" or _CHANNEL.match(key) or _CHANNELS.match(key):
        return True
    role, _, name = key.partition(".")
    if role == "GNSS-SDR":
        return name in GNSS_SDR_KEYS
    m = _SIGNAL_ROLE.match(role)
    family = m.group(1) if m else role
    return name in ROLE_KEYS.get(family, frozenset())


def unverified(keys: Iterable[str]) -> list[str]:
    """The keys that v0.0.22 would ignore, in input order."""
    return [k for k in keys if not is_verified(k)]
